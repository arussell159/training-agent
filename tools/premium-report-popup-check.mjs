// Production report-list -> popup journeys using isolated disposable APIs.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { spawn } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
const require = createRequire(import.meta.url);
const playwright = require(path.join(os.homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright"));
const engine = process.env.REPORT_ENGINE || "chromium";
const port = Number(process.env.REPORT_PORT || 5430);
const origin = `http://127.0.0.1:${port}`;
const output = `artifacts/premium-app/report-popups-${engine}`;
const server = spawn(process.execPath, ["tools/desktop-preview.mjs", "--calendar-edits", `--port=${port}`, `--dist=${process.env.REPORT_DIST || "ui/dist"}`], {stdio: ["ignore", "pipe", "pipe"]});
let browser;
const results = {engine, checks: [], errors: []};
const title = "Threshold intervals — recorded power and route";
try {
  await fs.mkdir(output, {recursive: true});
  await new Promise((resolve, reject) => {server.stdout.once("data", resolve); server.once("error", reject); server.once("exit", code => reject(Error(`Preview exited ${code}`)));});
  browser = await playwright[engine].launch({headless: true, ...(engine === "chromium" ? {channel: "msedge"} : {}), ...(process.env.REPORT_EXECUTABLE ? {executablePath: process.env.REPORT_EXECUTABLE} : {})});
  results.version = browser.version();
  for (const width of [1280, 1440]) {
    const context = await browser.newContext({viewport: {width, height: 820}, reducedMotion: "reduce", serviceWorkers: "block"});
    await context.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    page.on("pageerror", error => results.errors.push(error.message));
    page.on("console", message => {if (message.type() === "error") results.errors.push(message.text());});
    await page.goto(`${origin}/workout-reports`, {waitUntil: "networkidle"});
    const table = page.locator('[aria-label="Workout report table"]');
    const link = table.getByRole("link", {name: new RegExp(title)});
    await link.waitFor();
    const selectedSport = (await link.innerText()).split("·").at(-1).trim();
    await page.getByRole("combobox", {name: "Sport", exact: true}).click();
    await page.getByRole("option", {name: selectedSport, exact: true}).click();
    await link.waitFor();
    const selection = page.getByRole("checkbox", {name: new RegExp(`Select ${title} on`)});
    await selection.check();
    await table.evaluate(node => {node.dataset.reviewMounted = "retained";});
    await page.evaluate(() => window.scrollTo(0, 100));
    await link.scrollIntoViewIfNeeded();
    const scrollY = await page.evaluate(() => window.scrollY);
    const popup = page.getByRole("dialog", {name: title, exact: true});
    await link.click();
    await popup.waitFor();
    await popup.locator(".analysis-inspector-primary").waitFor();
    assert.equal(new URL(page.url()).searchParams.get("workout"), "event:9004");
    assert.equal(await table.getAttribute("data-review-mounted"), "retained");
    assert.equal(await page.locator(".desktop-app-header h1").textContent(), "Workout Reports");
    const box = await popup.boundingBox();
    assert.ok(box.x >= -1 && box.y >= -1 && box.x + box.width <= width + 1 && box.y + box.height <= 821, JSON.stringify(box));
    await page.screenshot({path: `${output}/${width}-analysis.png`});
    results.focusBeforeEscape = await page.evaluate(() => ({active: document.activeElement?.outerHTML?.slice(0, 600), url: location.href, dialogs: [...document.querySelectorAll('[role="dialog"], [role="alertdialog"]')].map(node => ({title: node.getAttribute('aria-labelledby'), text: node.textContent?.slice(0, 400)}))}));
    await page.keyboard.press("Escape");
    results.focusAfterEscape = await page.evaluate(() => ({active: document.activeElement?.outerHTML?.slice(0, 600), url: location.href, dialogs: [...document.querySelectorAll('[role="dialog"], [role="alertdialog"]')].map(node => ({title: node.getAttribute('aria-labelledby'), text: node.textContent?.slice(0, 400)}))}));
    await page.screenshot({path: `${output}/${width}-after-escape.png`});
    await popup.waitFor({state: "hidden"});
    await page.waitForFunction(() => !new URL(location.href).searchParams.has("workout"));
    assert.equal(await table.getAttribute("data-review-mounted"), "retained");
    assert.equal(await selection.isChecked(), true);
    assert.equal(await page.getByRole("combobox", {name: "Sport", exact: true}).innerText(), selectedSport);
    assert.ok(Math.abs((await page.evaluate(() => window.scrollY)) - scrollY) <= 4, "Closing restores report scroll");
    assert.equal(await link.evaluate(node => node === document.activeElement), true, "Closing restores report-row focus");
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).overflow === "hidden"), false);
    await link.click();
    await popup.waitFor();
    await popup.locator(".analysis-inspector-primary").waitFor();
    await popup.getByRole("button", {name: "Summary", exact: true}).click();
    const descriptionInput = popup.getByRole("textbox", {name: "Workout description", exact: true});
    const originalDescription = await descriptionInput.inputValue();
    await page.evaluate(() => {window.reportInputEvents = []; for (const type of ["compositionstart", "compositionend", "keydown", "input"]) document.addEventListener(type, event => window.reportInputEvents.push({type, key: event.key, inputType: event.inputType, time: performance.now(), composing: event.isComposing}), true);});
    await descriptionInput.fill("Disposable report draft — preserve on cancel");
    await page.keyboard.press("Escape");
    results.afterDraftEscape = await page.evaluate(() => ({inputEvents: window.reportInputEvents, active: document.activeElement?.outerHTML?.slice(0, 600), url: location.href, dialogs: [...document.querySelectorAll('[role="dialog"], [role="alertdialog"]')].map(node => ({title: node.getAttribute('aria-labelledby'), text: node.textContent?.slice(-1000)}))}));
    await page.screenshot({path: `${output}/${width}-draft-escape.png`});
    const discard = page.getByRole("alertdialog", {name: "Discard unsaved changes?", exact: true});
    await discard.getByRole("button", {name: "Cancel", exact: true}).click();
    await discard.waitFor({state: "hidden"});
    assert.equal(await descriptionInput.inputValue(), "Disposable report draft — preserve on cancel");
    await popup.getByRole("button", {name: "Analyze", exact: true}).click();
    await popup.locator(".analysis-inspector-primary").waitFor();
    assert.equal(await popup.getByRole("button", {name: "Save", exact: true}).isEnabled(), true, "Analysis retains save for a modified draft");
    assert.equal(await popup.getByRole("button", {name: "Save & Close", exact: true}).isVisible(), true);
    assert.equal(await popup.locator(".desktop-workout-auto-calculate").isVisible(), false);
    await popup.getByRole("button", {name: "Summary", exact: true}).click();
    assert.equal(await descriptionInput.inputValue(), "Disposable report draft — preserve on cancel", "View changes retain the draft");
    await descriptionInput.fill(originalDescription);
    await popup.getByRole("button", {name: "Analyze", exact: true}).waitFor();
    await page.screenshot({path: `${output}/${width}-summary.png`});
    await popup.getByRole("button", {name: "Analyze", exact: true}).click();
    await popup.locator(".analysis-inspector-primary").waitFor();
    assert.equal(await table.getAttribute("data-review-mounted"), "retained");
    await page.goBack();
    await popup.waitFor({state: "hidden"});
    assert.equal(await selection.isChecked(), true);
    await page.goForward();
    await popup.waitFor();
    await popup.getByRole("button", {name: "Close", exact: true}).click();
    await popup.waitFor({state: "hidden"});
    assert.equal(new URL(page.url()).pathname, "/workout-reports");
    await page.goto(`${origin}/workout-reports?workout=event%3A9004`, {waitUntil: "networkidle"});
    await popup.waitFor();
    await popup.getByRole("button", {name: "Close workout details", exact: true}).click();
    await popup.waitFor({state: "hidden"});
    assert.equal(new URL(page.url()).pathname, "/workout-reports");
    assert.equal(new URL(page.url()).searchParams.has("workout"), false);
    await table.waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    results.checks.push({width, reportListMounted: true, popupSummary: true, analysisOpensDirectlyInsidePopup: true, selectionAndFilterRetained: true, scrollAndFocusRestored: true, escape: true, realDraftGuardAndCancel: true, dirtyAnalysisSaveControls: true, cleanAnalysisClose: true, backForward: true, directLinkClose: true, noOverflow: true});
    await context.close();
  }
  {
    const context = await browser.newContext({viewport: {width: 1280, height: 820}, reducedMotion: "reduce", serviceWorkers: "block"});
    await context.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    page.on("pageerror", error => results.errors.push(error.message));
    page.on("console", message => {if (message.type() === "error") results.errors.push(message.text());});
    await page.goto(`${origin}/workout-reports`, {waitUntil: "networkidle"});
    const title = "Completed Strength — paired prescription";
    const link = page.locator('[aria-label="Workout report table"]').getByRole("link", {name: new RegExp(title)});
    await link.click();
    const analysis = page.getByRole("dialog", {name: title, exact: true});
    await analysis.getByRole("button", {name: "Summary", exact: true}).click();
    const summary = page.getByRole("dialog", {name: "Completed Strength Workout", exact: true});
    await summary.getByRole("button", {name: "Close completed Strength workout", exact: true}).click();
    await summary.waitFor({state: "hidden"});
    await page.waitForFunction(() => !new URL(location.href).searchParams.has("workout"));
    assert.equal(await link.evaluate(node => node === document.activeElement), true, "Strength Summary restores report-row focus");
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).overflow === "hidden"), false);
    results.checks.push({strengthAnalysisToSummary: true, rowFocusRestored: true, close: true});
    await context.close();
  }
  assert.deepEqual(results.errors, []);
  results.passed = true;
} finally {
  await fs.mkdir(output, {recursive: true});
  await fs.writeFile(`${output}/results.json`, JSON.stringify(results, null, 2) + "\n");
  console.log(JSON.stringify(results, null, 2));
  await browser?.close();
  server.kill();
}
